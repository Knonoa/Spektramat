/** Small native-precision fixtures generated by tools/host/run_raster.ps1. */
@RunWith(AndroidJUnit4::class)
class PrinterOriginalTest {
    @Test fun nativeExportRemainsIndependentOfProxySizeForPngTiffAndRaw() = assertNativeExports(
        "export-fixtures", listOf("rgb16.png", "rgb16.tif", "linear-float.tif", "sensor14.dng"),
    )

    @Test fun heicAndMotionPhotoExportTheFullResolutionStill() {
        org.junit.Assume.assumeTrue(Build.VERSION.SDK_INT >= 34)
        assertNativeExports("phone-formats", listOf("sdr.heic", "sdr.avif", "motion.jpg"))
    }

    private fun assertNativeExports(folder: String, files: List<String>) = runBlocking {
        val app = ApplicationProvider.getApplicationContext<LatentApp>()
        val startup = withTimeout(120_000) { app.startup.first { it is Startup.Ready } as Startup.Ready }
        val assets = InstrumentationRegistry.getInstrumentation().context.assets
        val look = Look(grain = 0f, halation = 0f, glare = 0f, interLayer = 0f,
            model = PhotoModel(outputCctfEncoding = false))
        for (name in files) {
            val file = File(app.cacheDir, "original-test-${System.nanoTime()}-$name")
            val proxyDir = File(app.cacheDir, "original-proxy-${System.nanoTime()}")
            val store = PhotoProxyStore(app, proxyDir)
            try {
                assets.open("$folder/$name").use { input -> file.outputStream().use { input.copyTo(it) } }
                val originalHash = hash(file)
                val size = Decoder.size(file)!!
                val frame = Frame(-88771L, -1L, 1, file, name, name.endsWith("dng"), size[0], size[1],
                    0L, "", "", 0, 0.0, 0.0, 0.0, 0f, look, file, 1)
                // Deliberately warm a tiny display source. Export must reread the native file.
                store.acquire(frame, "", true, 1).use { assertEquals(1, maxOf(it.width, it.height)) }
                val expected = Decoder.decode(file, 0, look.lensShading, look.aspect).use { original ->
                    FilmEngine.developFloat(original, look.photoGrade(), look.photoOrder(frame.id * 7919L + 1L),
                        look.finish(), look.finishTable())
                }
                expected.use {
                    val printed = Printer.print(app, startup.library, frame, look, 0, PrintFormat.DNG) { }
                    try {
                        assertEquals(name, size[0], printed.width); assertEquals(name, size[1], printed.height)
                        val bytes = app.contentResolver.openInputStream(printed.uri)!!.use { it.readBytes() }
                        val expectedSamples = expected.pixels().asFloatBuffer()
                        val saved = File(app.cacheDir, "original-result-${System.nanoTime()}.dng")
                        try {
                            saved.writeBytes(bytes)
                            Decoder.decode(saved, 0).use { decoded ->
                                assertFalse(decoded.previewOnly)
                                val actual = decoded.pixels().asFloatBuffer()
                                assertEquals(expectedSamples.remaining(), actual.remaining())
                                for (i in 0 until actual.remaining())
                                    assertEquals("$name native sample $i", expectedSamples[i], actual[i], .002f)
                            }
                        } finally { saved.delete() }
                    } finally {
                        printed.shown.recycle()
                        app.contentResolver.delete(printed.uri, null, null)
                    }
                }
                assertArrayEquals("$name original bytes", originalHash, hash(file))
            } finally {
                store.clearMemory(); file.delete()
                proxyDir.listFiles()?.forEach { it.delete() }
                proxyDir.delete()
            }
        }
    }

    private fun hash(file: File) = MessageDigest.getInstance("SHA-256").digest(file.readBytes())
}
