"""Generate matrix/TRC ICC v4 profiles for the app's output contracts.

No third-party profile files are copied. Primaries and decoding curves match
colour-science's standard RGB spaces used by the reference engine.
"""
from pathlib import Path
import struct

import numpy as np

OUT = Path(__file__).resolve().parents[1] / "engine/src/main/assets/icc"


def fixed(value):
    return struct.pack(">i", round(float(value) * 65536))


def xyz(value):
    return b"XYZ \0\0\0\0" + b"".join(fixed(x) for x in value)


def text(value):
    data = value.encode("utf-16-be")
    return b"mluc\0\0\0\0" + struct.pack(">II4sII", 1, 12, b"enUS", len(data), 28) + data


def generate(key, name, primaries, white, encoded):
    def white_xyz(xy):
        x, y = xy
        return np.array([x / y, 1, (1 - x - y) / y])
    matrix = np.array([[x / y, 1, (1 - x - y) / y] for x, y in primaries]).T
    matrix = matrix @ np.diag(np.linalg.solve(matrix, white_xyz(white)))
    bradford = np.array([[.8951, .2664, -.1614], [-.7502, 1.7135, .0367], [.0389, -.0685, 1.0296]])
    d50 = white_xyz((.3457, .3585))
    adaptation = np.linalg.inv(bradford) @ np.diag((bradford @ d50) / (bradford @ white_xyz(white))) @ bradford
    pcs = adaptation @ matrix
    curve = [1.]
    curve_type = 0
    if encoded:
        if key in ("srgb", "p3"):
            curve_type, curve = 4, [2.4, 1 / 1.055, .055 / 1.055, 1 / 12.92, .04045, 0, 0]
        elif key == "adobe":
            curve = [563 / 256]
        else:
            curve_type, curve = 4, [1.8, 1, 0, 1 / 16, .03125, 0, 0]
    trc = b"para\0\0\0\0" + struct.pack(">HH", curve_type, 0) + b"".join(fixed(v) for v in curve)
    label = name + ("" if encoded else " (linear)")
    tags = [(b"desc", text(label)), (b"cprt", text("Generated by Spektramat; standard RGB matrix/TRC definitions.")),
            (b"wtpt", xyz(d50)), (b"chad", b"sf32\0\0\0\0" + b"".join(fixed(x) for x in adaptation.ravel()))]
    tags += [(c + b"XYZ", xyz(pcs[:, i])) for i, c in enumerate((b"r", b"g", b"b"))]
    tags += [(c + b"TRC", trc) for c in (b"r", b"g", b"b")]
    offset = 132 + 12 * len(tags)
    records, payload = b"", b""
    for signature, data in tags:
        records += signature + struct.pack(">II", offset, len(data))
        data += b"\0" * (-len(data) % 4)
        payload += data
        offset += len(data)
    header = bytearray(128)
    struct.pack_into(">I4sI4s4s4s", header, 0, offset, b"spkt", 0x04300000, b"mntr", b"RGB ", b"XYZ ")
    struct.pack_into(">6H", header, 24, 2026, 11, 12, 0, 0, 0)
    header[36:40] = b"acsp"
    struct.pack_into(">I", header, 64, 1)  # relative colorimetric
    header[68:80] = b"".join(fixed(v) for v in (.9642, 1, .8249))
    header[80:84] = b"spkt"
    (OUT / (key + ("-encoded.icc" if encoded else "-linear.icc"))).write_bytes(
        header + struct.pack(">I", len(tags)) + records + payload)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for key, name, primaries, white in (
        ("srgb", "sRGB", ((.64,.33),(.30,.60),(.15,.06)), (.3127,.3290)),
        ("p3", "Display P3", ((.68,.32),(.265,.69),(.15,.06)), (.3127,.3290)),
        ("adobe", "Adobe RGB (1998)", ((.64,.33),(.21,.71),(.15,.06)), (.3127,.3290)),
        ("prophoto", "ProPhoto RGB", ((.7347,.2653),(.1596,.8404),(.0366,.0001)), (.3457,.3585)),
    ):
        for encoded in (False, True):
            generate(key, name, primaries, white, encoded)
